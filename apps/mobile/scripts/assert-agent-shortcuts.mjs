import { readFileSync, readdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

// The contract is a CommonJS-style `.js` module, so this script loads it the
// way `plugins/withAgentShortcuts.js` does — `require`, not a second import
// shape — and reads the ids, urls and resource names from that one definition.
const require = createRequire(import.meta.url);
const {
  AGENT_CONTROLS,
  AGENT_SHORTCUTS_META_DATA,
  AGENT_SHORTCUTS_RESOURCE,
} = require('../src/lib/agent-controls.js');

// Android's one-tap agent controls are two static app shortcuts. The launcher
// shows neither until the manifest's launcher activity carries the
// `android.app.shortcuts` meta-data, and a shortcut whose label resource is
// missing is dropped from the long-press menu — so plugins/withAgentShortcuts.js
// writes three things and this script proves all three survived the prebuild:
//   1. `res/xml/<AGENT_SHORTCUTS_RESOURCE>.xml` — one `<shortcut>` per contract
//      entry, each with one VIEW intent at that control's url;
//   2. `AndroidManifest.xml` — exactly one `android.app.shortcuts` meta-data,
//      on `.MainActivity`, resolving to the resource file above. The manifest is
//      regenerated by plugins/withAndroidManifestFix.js, so a duplicate or a
//      missing meta-data is a real defect and never a stale-tree artifact;
//   3. the label resources — English in `values/strings.xml`, one
//      `values-b+<tag>/` folder per other language. Android resolves
//      `@string/…` through the resource system, so an empty folder is a
//      language whose menu entry shows no label.
//
// The sibling `scripts/assert-widget-sources-unique.mjs` proves the iOS twin
// from a fresh prebuild; this is the Android one. Both read the tree the
// prebuild wrote and fail the command rather than the device.
//
// The ids, urls and resource names come from `src/lib/agent-controls.js` — the
// module the plugin reads — so this is a second reader of one contract, never a
// copy of it.
const META_DATA_NAME = 'android.app.shortcuts';
// Mirrors app.config.ts's `android.package`; the plugin derives the launcher
// activity from the same value. A change there must update the plugin and this
// script together, the same mirror `scripts/assert-expo-config.mjs` keeps.
const TARGET_PACKAGE = 'com.kilocode.kiloapp';
const TARGET_CLASS = 'com.kilocode.kiloapp.MainActivity';
const LAUNCHER_ACTIVITY = '.MainActivity';
// English is the default `values/` resources; the plugin writes `values-b+<tag>`
// for the other languages only, so a `values-b+en/` folder — which another
// plugin writes for its own strings — is not expected to carry these labels.
const ENGLISH_TAG = 'en';

const mobileDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const resDir = join(mobileDir, 'android', 'app', 'src', 'main', 'res');
const manifestPath = join(mobileDir, 'android', 'app', 'src', 'main', 'AndroidManifest.xml');
const shortcutsPath = join(resDir, 'xml', `${AGENT_SHORTCUTS_RESOURCE}.xml`);
const defaultStringsPath = join(resDir, 'values', 'strings.xml');

const failures = [];

/**
 * One XML element's attribute text by attribute name, or `undefined` when the
 * element does not carry it. The generated files quote every value.
 * @param {string} attributes
 * @param {string} name
 * @returns {string | undefined}
 */
function attribute(attributes, name) {
  return new RegExp(`(?:^|\\s)${name}="([^"]*)"`).exec(attributes)?.[1];
}

/**
 * Read one file of the generated tree, or record the prebuild named in the
 * failure list. A missing tree is the one failure that names its own cause.
 * @param {string} path
 * @returns {string | undefined}
 */
function readGenerated(path) {
  try {
    return readFileSync(path, 'utf8');
  } catch (error) {
    failures.push(
      `Cannot read ${path}: ${error.message} — run \`expo prebuild --platform android\` first`
    );
    return undefined;
  }
}

/** The control each contract id carries, for its url. */
const controlsById = new Map(AGENT_CONTROLS.map(control => [control.id, control]));

/** The label resources of every contract entry, in contract order. */
const labelResources = AGENT_SHORTCUTS_META_DATA.flatMap(metadata => [
  metadata.shortLabelResource,
  metadata.longLabelResource,
]);

// 1. The shortcut file: one `<shortcut>` per contract entry, each with exactly
//    one VIEW intent aimed at the app's own launcher activity and the control's
//    url.
const shortcutsSource = readGenerated(shortcutsPath);
const shortcutBlocks =
  shortcutsSource === undefined
    ? []
    : [...shortcutsSource.matchAll(/<shortcut\b([^>]*)>([\s\S]*?)<\/shortcut>/g)].map(match => ({
        attributes: match[1],
        body: match[2],
      }));

const contractShortcutIds = new Set(AGENT_SHORTCUTS_META_DATA.map(metadata => metadata.shortcutId));
for (const block of shortcutBlocks) {
  const shortcutId = attribute(block.attributes, 'android:shortcutId');
  if (shortcutId === undefined || !contractShortcutIds.has(shortcutId)) {
    failures.push(
      `<shortcut android:shortcutId="${shortcutId ?? '(none)'}"> is not a contract shortcut`
    );
  }
}

for (const metadata of AGENT_SHORTCUTS_META_DATA) {
  const control = controlsById.get(metadata.id);
  if (control === undefined) {
    failures.push(
      `the contract carries no control \`${metadata.id}\` for shortcut ${metadata.shortcutId}`
    );
    continue;
  }
  const matching = shortcutBlocks.filter(
    block => attribute(block.attributes, 'android:shortcutId') === metadata.shortcutId
  );
  if (matching.length !== 1) {
    failures.push(
      `<shortcut android:shortcutId="${metadata.shortcutId}"> appears ${matching.length} times, expected exactly one`
    );
    continue;
  }
  const shortLabel = attribute(matching[0].attributes, 'android:shortcutShortLabel');
  if (shortLabel !== `@string/${metadata.shortLabelResource}`) {
    failures.push(
      `${metadata.shortcutId} carries shortLabel "${shortLabel ?? '(none)'}", expected "@string/${metadata.shortLabelResource}"`
    );
  }
  const longLabel = attribute(matching[0].attributes, 'android:shortcutLongLabel');
  if (longLabel !== `@string/${metadata.longLabelResource}`) {
    failures.push(
      `${metadata.shortcutId} carries longLabel "${longLabel ?? '(none)'}", expected "@string/${metadata.longLabelResource}"`
    );
  }
  const intents = [...matching[0].body.matchAll(/<intent\b([^>]*?)\/?>/g)].map(match => match[1]);
  if (intents.length !== 1) {
    failures.push(
      `${metadata.shortcutId} carries ${intents.length} <intent> elements, expected exactly one`
    );
    continue;
  }
  const [intent] = intents;
  const data = attribute(intent, 'android:data');
  if (data !== control.url) {
    failures.push(
      `${metadata.shortcutId} intent opens "${data ?? '(none)'}", expected "${control.url}"`
    );
  }
  const targetPackage = attribute(intent, 'android:targetPackage');
  if (targetPackage !== TARGET_PACKAGE) {
    failures.push(
      `${metadata.shortcutId} intent targets package "${targetPackage ?? '(none)'}", expected "${TARGET_PACKAGE}"`
    );
  }
  const targetClass = attribute(intent, 'android:targetClass');
  if (targetClass !== TARGET_CLASS) {
    failures.push(
      `${metadata.shortcutId} intent targets class "${targetClass ?? '(none)'}", expected "${TARGET_CLASS}"`
    );
  }
  const action = attribute(intent, 'android:action');
  if (action !== 'android.intent.action.VIEW') {
    failures.push(
      `${metadata.shortcutId} intent carries action "${action ?? '(none)'}", expected "android.intent.action.VIEW"`
    );
  }
}

/** The `android.app.shortcuts` meta-data entries inside one `<activity>` body. */
function shortcutMetaDataWithin(activityBody) {
  return [...activityBody.matchAll(/<meta-data\b([^>]*?)\/?>/g)].filter(
    match => attribute(match[1], 'android:name') === META_DATA_NAME
  ).length;
}

// 2. The manifest meta-data the launcher reads. Exactly one, on the launcher
//    activity, resolving to the shortcut file.
const manifestSource = readGenerated(manifestPath);
let shortcutsMetaData = [];
let metaDataOnLauncher = false;
if (manifestSource !== undefined) {
  shortcutsMetaData = [...manifestSource.matchAll(/<meta-data\b([^>]*?)\/?>/g)]
    .map(match => match[1])
    .filter(attributes => attribute(attributes, 'android:name') === META_DATA_NAME);
  const launcher = [...manifestSource.matchAll(/<activity\b([^>]*)>([\s\S]*?)<\/activity>/g)].find(
    match => attribute(match[1], 'android:name') === LAUNCHER_ACTIVITY
  );
  metaDataOnLauncher = launcher !== undefined && shortcutMetaDataWithin(launcher[2]) === 1;
}
if (shortcutsMetaData.length !== 1) {
  failures.push(
    `AndroidManifest.xml carries ${shortcutsMetaData.length} \`${META_DATA_NAME}\` meta-data entries, expected exactly one`
  );
} else {
  const resource = attribute(shortcutsMetaData[0], 'android:resource');
  if (resource !== `@xml/${AGENT_SHORTCUTS_RESOURCE}`) {
    failures.push(
      `the \`${META_DATA_NAME}\` meta-data resolves to "${resource ?? '(none)'}", expected "@xml/${AGENT_SHORTCUTS_RESOURCE}"`
    );
  }
  if (!metaDataOnLauncher) {
    failures.push(
      `the \`${META_DATA_NAME}\` meta-data is not on the ${LAUNCHER_ACTIVITY} activity, so the launcher lists no shortcut`
    );
  }
}

// 3. The labels. One `<string>` per resource name; a name defined twice in one
//    folder is the aapt2 duplicate-resource failure by another route.
const STRING_ENTRY = /<string\b([^>]*)>([\s\S]*?)<\/string>/g;

/**
 * Every `<string name="…">` value in one file or folder, keyed by resource name.
 * @param {string[]} sources
 * @returns {Map<string, string[]>}
 */
function stringResources(sources) {
  /** @type {Map<string, string[]>} */
  const byName = new Map();
  for (const source of sources) {
    for (const match of source.matchAll(STRING_ENTRY)) {
      const name = attribute(match[1], 'name');
      if (name === undefined) {
        continue;
      }
      byName.set(name, [...(byName.get(name) ?? []), match[2]]);
    }
  }
  return byName;
}

const defaultSource = readGenerated(defaultStringsPath);
const defaultResources = stringResources(defaultSource === undefined ? [] : [defaultSource]);
for (const resource of labelResources) {
  const values = defaultResources.get(resource) ?? [];
  if (values.length !== 1) {
    failures.push(
      `values/strings.xml carries ${values.length} \`${resource}\` resources, expected exactly one`
    );
  } else if (values[0].length === 0) {
    failures.push(`values/strings.xml carries an empty \`${resource}\` resource`);
  }
}

let localeDirectories = [];
try {
  localeDirectories = readdirSync(resDir).filter(name => name.startsWith('values-b+'));
} catch (error) {
  failures.push(`Cannot list ${resDir}: ${error.message}`);
}

/** The `values-b+<tag>` directories whose labels were expected and found. */
let localizedDirectories = 0;
let completeLocalizedDirectories = 0;
for (const directory of localeDirectories) {
  // `values-b+zh+Hans` → `zh-Hans`, the tag the plugin localized.
  const tag = directory.slice('values-b+'.length).replaceAll('+', '-');
  if (tag === ENGLISH_TAG) {
    continue;
  }
  localizedDirectories += 1;
  let files = [];
  try {
    files = readdirSync(join(resDir, directory)).filter(name => name.endsWith('.xml'));
  } catch (error) {
    failures.push(`Cannot list ${join(resDir, directory)}: ${error.message}`);
    continue;
  }
  const resources = stringResources(
    files.map(file => readGenerated(join(resDir, directory, file)) ?? '')
  );
  let complete = true;
  for (const resource of labelResources) {
    const values = resources.get(resource) ?? [];
    if (values.length === 0) {
      failures.push(`${directory} carries no \`${resource}\` resource`);
      complete = false;
    } else if (values.length > 1) {
      failures.push(
        `${directory} carries ${values.length} \`${resource}\` resources, expected exactly one`
      );
      complete = false;
    } else if (values[0].length === 0) {
      failures.push(`${directory} carries an empty \`${resource}\` resource`);
      complete = false;
    }
  }
  if (complete) {
    completeLocalizedDirectories += 1;
  }
}

console.log('Android agent shortcuts');
console.log(`  <shortcut> elements: ${shortcutBlocks.length}`);
for (const metadata of AGENT_SHORTCUTS_META_DATA) {
  const matching = shortcutBlocks.filter(
    block => attribute(block.attributes, 'android:shortcutId') === metadata.shortcutId
  );
  console.log(`  ${metadata.shortcutId} <shortcut> elements: ${matching.length}`);
}
console.log(`  \`${META_DATA_NAME}\` meta-data entries: ${shortcutsMetaData.length}`);
console.log(
  `  values/strings.xml shortcut labels: ${
    labelResources.filter(resource => (defaultResources.get(resource) ?? []).length === 1).length
  }/${labelResources.length}`
);
console.log(
  `  values-b+* directories carrying every shortcut label: ${completeLocalizedDirectories}/${localizedDirectories}`
);

if (failures.length > 0) {
  console.error('Agent shortcut violations:');
  for (const failure of failures) {
    console.error(`  - ${failure}`);
  }
  process.exit(1);
}

console.log(
  `Android agent shortcuts OK: one <shortcut> per contract entry, each with one VIEW intent, exactly one \`${META_DATA_NAME}\` meta-data on ${LAUNCHER_ACTIVITY}, and every shortcut label resource defined`
);
