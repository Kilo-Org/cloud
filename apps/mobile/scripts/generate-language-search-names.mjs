import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { runIfMain } from '../../../tools/lib/entry-point.mjs';

const mobileDir = join(dirname(fileURLToPath(import.meta.url)), '..');
// Deliberately not `language-search-names`: that is the loader module's own
// basename, and a directory of the same name beside it makes `../language-search-names`
// resolve to the directory in Node and Vitest.
export const OUTPUT_DIR = join(mobileDir, 'src', 'i18n', 'language-search-name-tables');

const { LANGUAGE_ENGLISH_NAMES, LANGUAGE_ENDONYMS, SUPPORTED_LANGUAGES } =
  await import('../src/i18n/languages.ts');
const { foldForSearch } = await import('../src/i18n/fold-for-search.ts');

/** The tags every generated file and the loader map are keyed by. */
export const LANGUAGES = SUPPORTED_LANGUAGES;

/** The one export name of every generated module. */
export const EXPORT_NAME = 'names';

/**
 * Encodes a name as a single-quoted string literal that holds the name as
 * data. JSON.stringify supplies the escaping for quotes, backslashes and
 * control characters; its double quotes are unescaped and single quotes
 * escaped, so the literal keeps the repository's single-quote style.
 */
function formatNameLiteral(value) {
  const escaped = JSON.stringify(value)
    .slice(1, -1)
    .replaceAll(String.raw`\"`, '"')
    .replaceAll("'", String.raw`\'`);
  return `'${escaped}'`;
}

/**
 * The file name for a display language: kebab-case, because the lint config
 * refuses a capital in a file name.
 */
export function fileName(tag) {
  return `${tag.toLowerCase()}.ts`;
}

/** `zh-Hant` quotes its hyphen; `af` stays bare so the object reads plainly. */
function literalTag(tag) {
  return /^[A-Za-z][A-Za-z0-9]*$/.test(tag) ? tag : `'${tag}'`;
}

/**
 * The name `Intl.DisplayNames` reports for `tag` in the display language, or
 * undefined when the runtime cannot compute it or when the name adds nothing
 * the picker rows already search: the endonym and the English name are always
 * folded and matched, so a table entry equal to either would only be read
 * twice.
 */
export function keptDisplayName(displayNames, tag) {
  let name;
  try {
    name = displayNames.of(tag);
  } catch {
    return undefined;
  }
  if (name === undefined) {
    return undefined;
  }
  const folded = foldForSearch(name);
  if (folded === foldForSearch(LANGUAGE_ENDONYMS[tag])) {
    return undefined;
  }
  if (folded === foldForSearch(LANGUAGE_ENGLISH_NAMES[tag])) {
    return undefined;
  }
  return name;
}

/** One display language's kept names, in `SUPPORTED_LANGUAGES` order. */
export function collectLanguageSearchNames(displayTag) {
  // Constructed inside this function so a script run keeps `Intl` out of the
  // module scope, like the app's own `intl-cache` does.
  const displayNames = new Intl.DisplayNames([displayTag], { type: 'language', fallback: 'none' });
  const names = new Map();
  for (const tag of SUPPORTED_LANGUAGES) {
    const name = keptDisplayName(displayNames, tag);
    if (name !== undefined) {
      names.set(tag, name);
    }
  }
  return names;
}

/** The generated module's source for one display language's names. */
export function generateLanguageSearchNamesSource(
  displayTag,
  names = collectLanguageSearchNames(displayTag)
) {
  // Two-space key indentation, a named export and no import: the generated
  // file must be byte-identical to what `oxfmt` and the lint config want, so
  // the drift assert, `format:check` and `oxlint` all agree on it. The loader
  // types the record, so the module needs no type import of its own.
  const rows = [...names].map(([tag, name]) => `  ${literalTag(tag)}: ${formatNameLiteral(name)},`);
  return [
    '// generated by scripts/generate-language-search-names.mjs; do not edit by hand.',
    '',
    `export const ${EXPORT_NAME} = {`,
    ...rows,
    '};',
    '',
  ].join('\n');
}

runIfMain(
  () => {
    mkdirSync(OUTPUT_DIR, { recursive: true });
    let written = 0;
    let entries = 0;
    for (const displayTag of SUPPORTED_LANGUAGES) {
      const names = collectLanguageSearchNames(displayTag);
      entries += names.size;
      const file = join(OUTPUT_DIR, fileName(displayTag));
      writeFileSync(file, generateLanguageSearchNamesSource(displayTag, names));
      written += 1;
    }
    console.log(`Wrote ${written} language-search-name files with ${entries} names`);
  },
  import.meta.url
);
