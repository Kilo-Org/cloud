import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'jsonc-parser';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const v2Tag = process.argv[2] ?? 'kilo-v2';
if (v2Tag.startsWith('-')) throw new Error('Usage: node scripts/prepare-kilo2-local.mjs [npm-tag]');
const config = parse(await fs.readFile(path.join(root, 'wrangler.jsonc'), 'utf8'));
for (const container of config.env.dev.containers) {
  if (container.images?.app?.dockerfile === './Dockerfile.containers') {
    container.images.app.dockerfile = './Dockerfile.kilo2-containers';
  }
  if (container.image !== './Dockerfile.dev') continue;
  container.image_vars = { ...container.image_vars, KILO_RUNTIME_HARNESS: 'kilo2' };
}
await fs.writeFile(
  path.join(root, 'Dockerfile.kilo2-containers'),
  (await fs.readFile(path.join(root, 'Dockerfile.containers'), 'utf8')) +
    '\n# Local Kilo v2 proof runtime, installed from the npm channel. Generated by\n' +
    '# prepare-kilo2-local.mjs. The package shares the @kilocode/cli name with v1,\n' +
    '# so it uses its own npm prefix to keep the default `kilo` binary intact.\n' +
    `RUN npm install --global --prefix /opt/kilo2 @kilocode/cli@${v2Tag} \\\n` +
    ' && ln -sf /opt/kilo2/bin/kilo2 /usr/local/bin/kilo2\n' +
    'ENV KILO_RUNTIME_HARNESS=kilo2\n'
);
await fs.writeFile(
  path.join(root, 'wrangler.kilo2-local.json'),
  JSON.stringify(config, null, 2) + '\n'
);
console.log(
  "Prepared local Kilo v2 image configuration. Restart this worktree's Cloud Agent Worker."
);
