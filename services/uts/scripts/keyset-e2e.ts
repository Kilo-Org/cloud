/**
 * Local end-to-end run of the UTS key set: the mint Worker's 16 signer objects and 8 key-set
 * shards behind the feed Worker's `/.well-known/jwks.json`, both Workers under `wrangler dev`
 * over one persisted state directory and a fresh identity-store database.
 *
 * 1. A fresh set: 36 keys (two per signer, two per feed object), `Age` and
 *    `Kilo-Key-Set-Oldest-Age` under 17 seconds, cache windows that end with the 24-hour hold, no
 *    private key part, and RFC 8414 metadata that names the issuer and the feed key set.
 * 2. A token signed through `/__dev/sign` verifies against the published set with jose, and a
 *    tampered one does not. A claim set that outlives an hour, and an expired one, are refused.
 * 3. A restart over the same state keeps the same kids and public keys, bootstraps no signer
 *    again, and the token signed before it still verifies. An internet request to the old
 *    `/internal/signer-keys` path is a 404.
 * 4. An intruder Worker whose binding carries another caller gets no keys, and the mint Worker
 *    logs the refused caller.
 * 5. With the mint Worker stopped, the feed Worker serves its held set with both ages.
 * 6. With signer 07's stored state corrupted and signer 03's storage deleted, one read replaces
 *    signer 03's keys while signer 07's held keys stand in; only signer 03 bootstraps.
 * 7. Signer 07 stays broken past the feed Worker's 17-second window, then a cold start of both
 *    Workers over a restarted shard still serves signer 07's held keys.
 *
 * Synthetic data only: every key is generated by the Worker objects for the run, and the database
 * passwords are random per run. No secret is printed.
 *
 *   UTS_E2E_ADMIN_URL  admin login to the identity-store database (loopback only)
 *   UTS_E2E_PORT       first of the run's ports (default 9300): the mint Worker and its inspector,
 *                      then the feed Worker and its inspector at +2 and +3, then the intruder
 *                      Worker and its inspector at +4 and +5
 *
 * The run drops and recreates the database `uts_keyset_e2e`, applies the migrations and writes the
 * run's logs under a new temporary directory, whose path it prints. It stops its Workers when it
 * ends, also on SIGINT (exit 130) or SIGTERM (exit 143).
 */
