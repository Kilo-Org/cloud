const JwksSchema = z.object({
  keys: z.array(z.object({ kid: z.string() }).catchall(z.unknown())),
});
type Jwks = z.infer<typeof JwksSchema>;
const MetadataSchema = z.object({ issuer: z.url(), jwks_uri: z.url() });
const SignResponseSchema = z.object({ signer: z.number(), kid: z.string(), token: z.string() });

let failures = 0;

function log(step: string, detail: unknown): void {
  console.log(`${step.padEnd(46)} ${typeof detail === 'string' ? detail : JSON.stringify(detail)}`);
}

function check(condition: boolean, message: string): void {
  if (condition) {
    console.log(`PASS ${message}`);
    return;
  }
  failures += 1;
  console.log(`FAIL ${message}`);
}

type Worker = { label: string; child: ChildProcess };

const logs = new Map<string, string[]>();
let mint: Worker | undefined;
let feed: Worker | undefined;
let intruder: Worker | undefined;
let admin: pg.Client | undefined;

/** Set once cleanup starts; no Worker starts after it. */
let cleaning: Promise<void> | undefined;

/** Rejects when a Worker process cannot be spawned; the start-up waits race on it. */
const { promise: spawnFailed, reject: failSpawn } = Promise.withResolvers<never>();
spawnFailed.catch(() => undefined);

function start(
  label: string,
  cwd: string,
  args: readonly string[],
  env: NodeJS.ProcessEnv = {}
): Worker {
  if (cleaning !== undefined) throw new Error('the run is stopping');
  const lines: string[] = [];
  logs.set(label, lines);
  const file = createWriteStream(join(LOGS, `${label}.log`), { flags: 'a' });
  const child = spawn('./node_modules/.bin/wrangler', [...args], {
    cwd,
    detached: true,
    stdio: ['ignore', 'pipe', 'pipe'],
    env: {
      ...process.env,
      WRANGLER_REGISTRY_PATH: join(WORK, 'registry'),
      XDG_CONFIG_HOME: join(WORK, 'xdg'),
      WRANGLER_SEND_METRICS: 'false',
      ...env,
    },
  });
  const collect = (chunk: Buffer) => {
    lines.push(chunk.toString());
    file.write(chunk);
  };
  child.stdout?.on('data', collect);
  child.stderr?.on('data', collect);
  child.once('exit', () => file.end());
  child.once('error', error => failSpawn(new Error(`${label} did not start: ${error.message}`)));
  return { label, child };
}

function logText(label: string): string {
  return (logs.get(label) ?? []).join('');
}

function waitForExit(child: ChildProcess, ms: number): Promise<boolean> {
  if (child.exitCode !== null || child.signalCode !== null) return Promise.resolve(true);
  const { promise, resolve } = Promise.withResolvers<boolean>();
  const onExit = () => {
    clearTimeout(timer);
    resolve(true);
  };
  const timer = setTimeout(() => {
    child.off('exit', onExit);
    resolve(false);
  }, ms);
  child.once('exit', onExit);
  return promise;
}

/** The `code` of a library error (`jose` sets one), or its message. */
function errorCode(error: unknown): string {
  if (
    typeof error === 'object' &&
    error !== null &&
    'code' in error &&
    typeof error.code === 'string'
  ) {
    return error.code;
  }
  return error instanceof Error ? error.message : String(error);
}

async function stop(worker: Worker | undefined): Promise<void> {
  const child = worker?.child;
  if (child?.pid === undefined) return;
  if (child.exitCode === null && child.signalCode === null) {
    try {
      process.kill(-child.pid, 'SIGTERM');
    } catch {
      // The Worker exited between the check and the signal.
    }
  }
  if (!(await waitForExit(child, 5000))) {
    try {
      process.kill(-child.pid, 'SIGKILL');
    } catch {
      // The Worker exited between the check and the signal.
    }
    await waitForExit(child, 5000);
  }
}

async function waitForHttp(url: string, name: string): Promise<void> {
  for (let attempt = 0; attempt < 90; attempt += 1) {
    const answered = await fetch(url).then(
      () => true,
      () => false
    );
    if (answered) return;
    await Promise.race([sleep(1000), spawnFailed]);
  }
  throw new Error(`${name} did not answer at ${url}`);
}

async function waitForClosed(url: string): Promise<void> {
  for (let attempt = 0; attempt < 60; attempt += 1) {
    const answered = await fetch(url).then(
      () => true,
      () => false
    );
    if (!answered) return;
    await sleep(500);
  }
  throw new Error(`${url} still answers after its Worker stopped`);
}

function startMint(label: string, urls: { app: string; pat: string; reader: string }): void {
  mint = start(
    label,
    UTS_DIR,
    [
      'dev',
      '-c',
      'wrangler.dev.jsonc',
      '--port',
      String(PORT),
      '--inspector-port',
      String(PORT + 1),
      '--persist-to',
      STATE,
    ],
    {
      CLOUDFLARE_HYPERDRIVE_LOCAL_CONNECTION_STRING_IDENTITY_STORE: urls.app,
      CLOUDFLARE_HYPERDRIVE_LOCAL_CONNECTION_STRING_IDENTITY_STORE_PAT: urls.pat,
      CLOUDFLARE_HYPERDRIVE_LOCAL_CONNECTION_STRING_IDENTITY_STORE_REPLICA: urls.reader,
    }
  );
}

function startFeed(label: string): void {
  feed = start(label, FEED_DIR, [
    'dev',
    '--env',
    'local',
    '--port',
    String(PORT + 2),
    '--inspector-port',
    String(PORT + 3),
    '--persist-to',
    STATE,
  ]);
}

async function stopMint(): Promise<void> {
  await stop(mint);
  mint = undefined;
  await waitForClosed(MINT);
}

async function stopAll(): Promise<void> {
  await stop(intruder);
  intruder = undefined;
  await stop(mint);
  mint = undefined;
  await stop(feed);
  feed = undefined;
  await waitForClosed(MINT);
  await waitForClosed(FEED);
}

/** Stops every Worker and closes the admin connection, once. */
function cleanup(): Promise<void> {
  cleaning ??= (async () => {
    await stopAll();
    await admin?.end().catch(() => undefined);
    console.log(`run directory: ${WORK}`);
  })();
  return cleaning;
}

// `on`, not `once`: pnpm and tsx pass the signal on again, and tsx ends the process when a signal
// finds no listener, before cleanup finishes. The first signal picks the exit code.
let signalled = false;
for (const [signal, code] of [
  ['SIGINT', 130],
  ['SIGTERM', 143],
] as const) {
  process.on(signal, () => {
    if (signalled) return;
    signalled = true;
    console.log(`keyset e2e: ${signal}, stopping`);
    void cleanup().finally(() => process.exit(code));
  });
}

function age(headers: Headers): number | null {
  const raw = headers.get('age');
  return raw !== null && /^\d+$/.test(raw.trim()) ? Number(raw) : null;
}

function oldestAge(headers: Headers): number | null {
  const raw = headers.get(UTS_JWKS_OLDEST_AGE_HEADER);
  return raw !== null && /^\d+$/.test(raw.trim()) ? Number(raw) : null;
}

/**
 * A standard HTTP cache serves a response fresh for max-age minus Age, and stale on error for
 * stale-if-error more; both must end when the oldest keys' 24-hour hold ends, to the second.
 */
function cacheWindow(headers: Headers, expectedMaxAge?: number): boolean {
  const control = headers.get('cache-control') ?? '';
  const maxAge = Number(/max-age=(\d+)/.exec(control)?.[1] ?? Number.NaN);
  const staleIfError = Number(/stale-if-error=(\d+)/.exec(control)?.[1] ?? Number.NaN);
  const currentAge = age(headers);
  const oldest = oldestAge(headers);
  if (currentAge === null || oldest === null) return false;
  if (!Number.isFinite(maxAge) || !Number.isFinite(staleIfError)) return false;
  const window = maxAge - currentAge + staleIfError;
  const holdLeft = 86_400 - oldest;
  console.log(
    `  cache-control max-age=${maxAge} stale-if-error=${staleIfError} age=${currentAge} oldest=${oldest}: windows end ${window} s after arrival, hold left ${holdLeft} s`
  );
  return (
    maxAge <= 300 &&
    staleIfError <= 86_400 &&
    window <= holdLeft &&
    window >= holdLeft - 1 &&
    (expectedMaxAge === undefined || maxAge === expectedMaxAge)
  );
}

async function jwks(): Promise<{ status: number; headers: Headers; body: Jwks }> {
  const response = await fetch(JWKS);
  return {
    status: response.status,
    headers: response.headers,
    body: JwksSchema.parse(await response.json()),
  };
}

function kids(body: Jwks): string[] {
  return body.keys.map(key => key.kid).sort();
}

function tokenKids(body: Jwks, signer: number): string[] {
  const prefix = `uts-token-${String(signer).padStart(2, '0')}-`;
  return kids(body).filter(kid => kid.startsWith(prefix));
}

function shardOf(label: string): number | null {
  const matches = [
    ...logText(label).matchAll(/"event":"uts\.key_set_shard\.started","shard":(\d)/g),
  ];
  const last = matches.at(-1);
  return last === undefined ? null : Number(last[1]);
}

function readLog(label: string): string {
  const file = join(LOGS, `${label}.log`);
  return readFileSync(file, 'utf8');
}

function* walk(dir: string): Generator<string> {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(path);
    else yield path;
  }
}

/** The durable-object storage of one signer, found by a kid its state carries. */
function signerStorage(signer: number): string {
  const marker = `uts-token-${String(signer).padStart(2, '0')}-`;
  const root = join(STATE, 'v3', 'do');
  if (!statSync(root, { throwIfNoEntry: false })?.isDirectory()) {
    throw new Error(`no durable-object storage under ${root}`);
  }
  const objects = readdirSync(root, { withFileTypes: true }).filter(
    entry => entry.isDirectory() && entry.name.includes('UtsSignerDO')
  );
  const bases = new Set<string>();
  for (const object of objects) {
    for (const file of walk(join(root, object.name))) {
      if (!file.includes('.sqlite')) continue;
      if (!readFileSync(file).includes(marker)) continue;
      bases.add(file.replace(/\.sqlite(-wal|-shm)$/, '.sqlite'));
    }
  }
  const [base] = [...bases];
  if (base === undefined || bases.size > 1) {
    throw new Error(`signer ${signer}: found ${bases.size} storages, expected 1`);
  }
  return base;
}

function breakSignerState(base: string): number {
  const database = new DatabaseSync(base);
  try {
    const result = database
      .prepare("UPDATE _cf_KV SET value = ? WHERE key = 'signer-state'")
      .run(serialize({ broken: true }));
    return Number(result.changes);
  } finally {
    database.close();
  }
}

type ClaimSet = { grantId: string; claims: Record<string, unknown> };

function claims(now: number): ClaimSet {
  return {
    grantId: 'grant-e2e-1',
    claims: {
      iss: issuer,
      exp: now + 600,
      aud: 'gateway',
      sub: 'user-e2e',
      client_id: 'kilo-cli',
      iat: now,
      jti: 'jti-e2e-1',
      scope: 'gateway:models.read',
      sid: 'grant-e2e-1',
      env: 'development',
    },
  };
}

async function sign(body: unknown): Promise<Response> {
  return await fetch(`${MINT}/__dev/sign`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify(body),
  });
}

/** A key set per call, so each verification fetches the set the feed Worker serves now. */
function remoteKeys() {
  // `jose` takes the Node `URL`; the Worker types' `URL` is a different class.
  return createRemoteJWKSet(new NodeUrl(JWKS));
}

async function verifiedKid(token: string): Promise<string> {
  const { protectedHeader } = await jwtVerify(token, remoteKeys(), {
    issuer,
    audience: 'gateway',
    typ: 'at+jwt',
    algorithms: ['EdDSA'],
  });
  return protectedHeader.kid ?? 'none';
}

async function refused(token: string): Promise<string> {
  return await jwtVerify(token, remoteKeys(), { algorithms: ['EdDSA'] }).then(
    () => 'accepted',
    error => errorCode(error)
  );
}

async function main(): Promise<void> {
  const store = await openE2eStore('uts_keyset_e2e');
  admin = store.admin;
  try {
    rmSync(STATE, { recursive: true, force: true });
    console.log(`== start 1: both Workers, fresh state at ${STATE}`);
    startMint('mint-1', store.urls);
    startFeed('feed-1');
    await waitForHttp(`${MINT}/`, 'the mint Worker');
    await waitForHttp(`${FEED}/`, 'the feed Worker');

    console.log('== JWKS');
    const first = await jwks();
    const keyCount = first.body.keys.length;
    const distinct = new Set(kids(first.body)).size;
    const tokenKeys = first.body.keys.filter(key => key.kid.startsWith('uts-token-')).length;
    const signers = new Set(
      first.body.keys
        .filter(key => key.kid.startsWith('uts-token-'))
        .map(key => key.kid.split('-')[2])
    ).size;
    const feedKeys = first.body.keys.filter(key => key.kid.startsWith('uts-feed-')).length;
    const firstAge = age(first.headers);
    const firstOldest = oldestAge(first.headers);
    log(
      'keys',
      `${keyCount}  distinct kids: ${distinct}  token keys: ${tokenKeys} of ${signers} signers  feed keys: ${feedKeys}`
    );
    log('first key', JSON.stringify(first.body.keys[0] ?? null));
    check(
      first.status === 200 && first.headers.get('content-type') === 'application/json',
      'JWKS answers 200 with JSON'
    );
    check(
      cacheWindow(first.headers, 300),
      'JWKS carries max-age=300 and cache windows that end with the 24-hour hold'
    );
    check(firstAge !== null && firstAge < 17, 'a fresh key set carries Age under 17 seconds');
    check(
      firstOldest !== null && firstOldest < 17,
      'a fresh key set carries Kilo-Key-Set-Oldest-Age under 17 seconds'
    );
    check(
      keyCount === KEYS &&
        distinct === KEYS &&
        tokenKeys === UTS_SIGNER_COUNT * 2 &&
        signers === UTS_SIGNER_COUNT &&
        feedKeys === UTS_FEED_COUNT * 2,
      `${KEYS} keys: ${UTS_SIGNER_COUNT * 2} token keys of ${UTS_SIGNER_COUNT} signers and ${UTS_FEED_COUNT * 2} feed keys`
    );
    check(
      first.body.keys.every(key => !('d' in key)),
      'no private key part in the key set'
    );

    console.log('== RFC 8414 metadata on the issuer');
    const metadataResponse = await fetch(METADATA);
    const metadata = MetadataSchema.parse(await metadataResponse.json());
    log('metadata', JSON.stringify(metadata));
    check(
      metadata.issuer === issuer && metadata.jwks_uri === jwksUri,
      'metadata names the issuer and the feed key set'
    );

    console.log(
      '== sign through the development route, verify with jose against the published JWKS'
    );
    const now = Math.floor(Date.now() / 1000);
    const claimSet = claims(now);
    const signed = await sign(claimSet);
    const signResponse = SignResponseSchema.parse(await signed.json());
    log('signed', { signer: signResponse.signer, kid: signResponse.kid });
    const header = await verifiedKid(signResponse.token).then(
      kid => ({ status: 'verified', kid }),
      error => ({ status: 'refused', kid: errorCode(error) })
    );
    const [head, payload, signature] = signResponse.token.split('.');
    const flipped = `${signature.slice(0, 10)}${signature[10] === 'A' ? 'B' : 'A'}${signature.slice(11)}`;
    const tampered = await refused([head, payload, flipped].join('.'));
    log('verified', header);
    log('tampered', tampered);
    check(
      header.status === 'verified' && tampered !== 'accepted',
      'the signed token verifies against the JWKS and a tampered one does not'
    );

    console.log('== refused claim set (exp 2 h ahead)');
    const tooLong = { ...claimSet, claims: { ...claimSet.claims, exp: now + 7200 } };
    const tooLongResponse = await sign(tooLong);
    const tooLongBody = await tooLongResponse.json();
    log('refused', `${JSON.stringify(tooLongBody)} ${tooLongResponse.status}`);
    check(
      tooLongResponse.status === 400 &&
        z.object({ error: z.string() }).parse(tooLongBody).error === 'invalid_claims',
      'a claim set that outlives 1 hour is refused'
    );

    console.log('== refused claim set (iat inside the skew, exp already past)');
    const expiredAt = Math.floor(Date.now() / 1000);
    const expired = {
      ...claimSet,
      claims: { ...claimSet.claims, iat: expiredAt - 30, exp: expiredAt - 1 },
    };
    const expiredResponse = await sign(expired);
    const expiredBody = await expiredResponse.json();
    log('refused', `${JSON.stringify(expiredBody)} ${expiredResponse.status}`);
    check(
      expiredResponse.status === 400 &&
        z.object({ error: z.string() }).parse(expiredBody).error === 'already_expired',
      'an already expired claim set is refused'
    );

    const beforeRestart = kids(first.body).join('\n');

    console.log('== stop both Workers');
    await stop(mint);
    mint = undefined;
    await stop(feed);
    feed = undefined;
    await waitForClosed(MINT);
    await waitForClosed(FEED);

    console.log('== start 2: same persisted state');
    startMint('mint-2', store.urls);
    startFeed('feed-2');
    await waitForHttp(`${MINT}/`, 'the mint Worker');
    await waitForHttp(`${FEED}/`, 'the feed Worker');
    const second = await jwks();
    check(kids(second.body).join('\n') === beforeRestart, 'same kids after the restart');
    check(
      JSON.stringify(
        second.body.keys
          .map(key => ({ ...key }))
          .sort((left, right) => left.kid.localeCompare(right.kid))
      ) ===
        JSON.stringify(
          first.body.keys
            .map(key => ({ ...key }))
            .sort((left, right) => left.kid.localeCompare(right.kid))
        ),
      'same public keys after the restart'
    );
    check(
      !readLog('mint-2').includes('uts.signer.bootstrapped'),
      'no signer bootstrapped again after the restart'
    );
    log(
      'bootstrap log lines',
      `first run: ${(readLog('mint-1').match(/uts\.signer\.bootstrapped/g) ?? []).length}  second run: ${(readLog('mint-2').match(/uts\.signer\.bootstrapped/g) ?? []).length}`
    );

    console.log('== the token signed before the restart still verifies');
    const afterRestart = await verifiedKid(signResponse.token).then(
      kid => ({ status: 'verified', kid }),
      error => ({ status: 'refused', kid: errorCode(error) })
    );
    log('verified after restart', afterRestart);
    check(afterRestart.status === 'verified', 'the pre-restart token verifies after the restart');

    console.log(
      '== an internet request to the internal signer-keys route gets the unknown-path answer'
    );
    const direct = await fetch(`${MINT}/internal/signer-keys`);
    const directBody = await direct.text();
    log('direct', `${directBody} ${direct.status}`);
    check(
      direct.status === 404 && directBody === '{"error":"not_found"}',
      'the internal route is a 404 without the feed caller'
    );

    console.log(
      '== intruder: a Worker whose binding to the mint Worker carries another caller name'
    );
    const intruderConfig = join(WORK, 'wrangler.intruder.jsonc');
    writeFileSync(
      intruderConfig,
      `${JSON.stringify(
        {
          name: 'uts-feed-intruder',
          main: join(FEED_DIR, 'src/index.ts'),
          compatibility_date: '2026-06-10',
          compatibility_flags: ['nodejs_compat'],
          vars: { UTS_ENVIRONMENT: 'development' },
          version_metadata: { binding: 'CF_VERSION_METADATA' },
          services: [
            {
              binding: 'UTS_MINT',
              service: 'uts-local',
              entrypoint: 'SignerKeys',
              props: { caller: 'o11y' },
            },
            {
              binding: 'UTS_FEED_READS',
              service: 'uts-local',
              entrypoint: 'FeedReads',
              props: { caller: 'o11y' },
            },
          ],
        },
        null,
        2
      )}\n`
    );
    intruder = start('intruder', FEED_DIR, [
      'dev',
      '-c',
      intruderConfig,
      '--port',
      String(PORT + 4),
      '--inspector-port',
      String(PORT + 5),
      '--persist-to',
      INTRUDER_STATE,
    ]);
    await waitForHttp(`http://127.0.0.1:${PORT + 4}`, 'the intruder Worker');
    const intruderUrl = `http://127.0.0.1:${PORT + 4}/.well-known/jwks.json`;
    const intruderResponse = await fetch(intruderUrl);
    const intruderBody = await intruderResponse.text();
    log('intruder', `${intruderBody} ${intruderResponse.status}`);
    await sleep(1000);
    check(
      intruderResponse.status === 500 && intruderBody === '{"error":"server_error"}',
      'the intruder gets no keys'
    );
    check(
      readLog('mint-2').includes('"event":"uts.signer_keys.refused","caller":"o11y"'),
      'the mint Worker logged the refused caller'
    );
    check(
      (await jwks()).body.keys.length === KEYS,
      `the real feed Worker still serves ${KEYS} keys`
    );
    await stop(intruder);
    intruder = undefined;

    console.log(
      '== the mint Worker stops: the feed Worker keeps serving its held set, with both ages'
    );
    const storedShards = [shardOf('mint-1'), shardOf('mint-2')];
    log("shards that stored all signers' keys", storedShards);
    await stopMint();
    await sleep(18_000);
    const held = await jwks();
    const heldAge = age(held.headers);
    const heldOldest = oldestAge(held.headers);
    log('held', { age: heldAge, oldest: heldOldest, keys: held.body.keys.length });
    check(
      held.body.keys.length === KEYS,
      `the feed Worker serves its ${KEYS} held keys while the mint Worker is down`
    );
    check(heldAge !== null && heldAge >= 17, 'the held set carries an Age of at least 17 seconds');
    check(
      heldOldest !== null && heldAge !== null && heldOldest === heldAge,
      'with every signer read failing, the oldest age equals Age'
    );
    check(cacheWindow(held.headers, 300), "the cache windows end with the oldest keys' hold");

    console.log("== signer 07's object fails to load while signer 03's keys change");
    const storage03 = signerStorage(3);
    const storage07 = signerStorage(7);
    log('signer 03 storage', storage03.replace(`${STATE}/`, ''));
    log('signer 07 storage', storage07.replace(`${STATE}/`, ''));
    for (const suffix of ['', '-wal', '-shm']) rmSync(`${storage03}${suffix}`, { force: true });
    const changed = breakSignerState(storage07);
    log('signer 07 rows changed', changed);
    startMint('mint-3', store.urls);
    await waitForHttp(`${MINT}/`, 'the mint Worker');

    let partial = await jwks();
    for (let attempt = 0; attempt < 30; attempt += 1) {
      if (JSON.stringify(tokenKids(partial.body, 3)) !== JSON.stringify(tokenKids(first.body, 3))) {
        break;
      }
      await sleep(2000);
      partial = await jwks();
    }
    const partialAge = age(partial.headers);
    const partialOldest = oldestAge(partial.headers);
    log('signer 03 kids before', tokenKids(first.body, 3));
    log('signer 03 kids after', tokenKids(partial.body, 3));
    await sleep(2000);
    check(
      tokenKids(partial.body, 3).filter(kid => !tokenKids(first.body, 3).includes(kid)).length ===
        2,
      "signer 03's new kids appear while signer 07 fails"
    );
    check(
      tokenKids(partial.body, 3).filter(kid => tokenKids(first.body, 3).includes(kid)).length === 0,
      "signer 03's old kids are gone"
    );
    check(
      JSON.stringify(tokenKids(partial.body, 7)) === JSON.stringify(tokenKids(first.body, 7)),
      "signer 07's held kids stay in the set"
    );
    const others = (body: Jwks) => kids(body).filter(kid => !/^uts-token-0[37]-/.test(kid));
    check(
      JSON.stringify(others(partial.body)) === JSON.stringify(others(first.body)),
      "the other 14 signers' kids are unchanged"
    );
    check(partial.body.keys.length === KEYS, `the key set still lists ${KEYS} keys`);
    check(
      partialAge !== null && partialAge < 17,
      'the set is fresh by Age while signer 07 fails: under 17 seconds'
    );
    check(
      partialOldest !== null && partialOldest >= 17,
      "the oldest age carries signer 07's held keys: at least 17 seconds"
    );
    check(cacheWindow(partial.headers, 300), "the cache windows end with the oldest keys' hold");
    check(
      readLog('mint-3').includes('"event":"uts.signer_keys.signer_failed","signer":7'),
      "the mint Worker logged signer 07's failed call"
    );
    check(
      (readLog('mint-3').match(/uts\.signer\.bootstrapped/g) ?? []).length === 1,
      'only signer 03 created new keys'
    );
    const thirdShard = shardOf('mint-3');
    if (thirdShard !== null && storedShards.includes(thirdShard)) {
      log('run 3 shard', `${thirdShard}, which stored signer 07's keys before`);
      check(
        /"event":"uts\.signer_keys\.signer_failed","signer":7,.*"heldReadAt":[0-9]+/.test(
          readLog('mint-3')
        ),
        "the restarted key-set shard stood in signer 07's stored keys"
      );
      check(
        !readLog('feed-2').includes('"event":"uts_feed.signer_keys.signers_failed"'),
        "the feed Worker got signer 07's keys from the restarted shard, not a failure"
      );
    } else {
      log(
        'run 3 shard',
        `${thirdShard}, which never read signer 07: the warm feed isolate keeps its own copy`
      );
      check(
        readLog('feed-2').includes(
          '"event":"uts_feed.signer_keys.signers_failed","failed":[{"signer":7,"status":"unavailable"}]'
        ),
        'the feed Worker logged signer 07 without keys in the answer'
      );
    }

    console.log("== signer 07 stays broken past the feed Worker's 17-second window");
    await sleep(20_000);
    const later = await jwks();
    const laterAge = age(later.headers);
    const laterOldest = oldestAge(later.headers);
    log('later', { age: laterAge, oldest: laterOldest });
    check(laterAge !== null && laterAge < 17, 'the set is still fresh by Age: under 17 seconds');
    check(
      laterOldest !== null && partialOldest !== null && laterOldest >= partialOldest + 20,
      'the oldest age grew by at least the 20 seconds waited'
    );
    check(
      JSON.stringify(tokenKids(later.body, 7)) === JSON.stringify(tokenKids(first.body, 7)),
      "signer 07's held kids still serve"
    );
    check(cacheWindow(later.headers, 300), "the cache windows end with the oldest keys' hold");

    console.log(
      '== cold start of both Workers while signer 07 still fails: new feed isolate, new key-set shards'
    );
    let cold: { body: Jwks; headers: Headers } | undefined;
    let coldShard: number | null = null;
    let coldMintLabel = '';
    let coldFeedLabel = '';
    for (let attempt = 1; attempt <= 12; attempt += 1) {
      await stopAll();
      coldMintLabel = `mint-4-${attempt}`;
      coldFeedLabel = `feed-3-${attempt}`;
      startMint(coldMintLabel, store.urls);
      startFeed(coldFeedLabel);
      await waitForHttp(`${MINT}/`, 'the mint Worker');
      await waitForHttp(`${FEED}/`, 'the feed Worker');
      cold = await jwks();
      await sleep(2000);
      coldShard = shardOf(coldMintLabel);
      log(`cold try ${attempt}`, `shard ${coldShard}: ${cold.body.keys.length} keys`);
      if (coldShard !== null && storedShards.includes(coldShard)) break;
    }
    if (cold === undefined) throw new Error('the cold start made no request');
    const coldOldest = oldestAge(cold.headers);
    check(
      coldShard !== null && storedShards.includes(coldShard),
      "the cold mint Worker drew a shard that stored signer 07's keys"
    );
    check(
      JSON.stringify(tokenKids(cold.body, 7)) === JSON.stringify(tokenKids(first.body, 7)),
      "a cold feed isolate over a restarted shard still serves signer 07's held kids"
    );
    check(cold.body.keys.length === KEYS, `the cold key set lists ${KEYS} keys`);
    check(
      coldOldest !== null && laterOldest !== null && coldOldest >= laterOldest,
      "the cold key set keeps signer 07's earlier read time: oldest age at least the last one"
    );
    check(
      !readLog(coldMintLabel).includes('uts.signer.bootstrapped'),
      'the cold restart created no keys'
    );
    check(cacheWindow(cold.headers, 300), "the cache windows end with the oldest keys' hold");
    check(
      !readLog(coldFeedLabel).includes('"event":"uts_feed.signer_keys.signers_failed"'),
      'the feed Worker got no failed signer in the cold answer'
    );

    if (failures === 0) console.log('keyset e2e: all checks passed');
    else {
      console.log(`keyset e2e: ${failures} check(s) failed`);
      process.exitCode = 1;
    }
  } finally {
    await cleanup();
  }
}

await main();
