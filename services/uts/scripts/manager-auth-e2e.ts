/**
 * Local end-to-end run of the manager login key: the mint Worker under `wrangler dev` and a
 * stand-in secrets manager on loopback that does what Infisical JWT Auth does at login. It fetches
 * the key set from the mint Worker's `/manager-auth/.well-known/jwks.json` and verifies the login
 * JWT against it with the exact issuer, subject and audience of the development identity.
 *
 * 1. Before any login the key set is empty.
 * 2. `POST /__dev/manager/write` logs in with a login JWT, creates a rotation secret in
 *    `/admin/identity-store` (the stand-in answers with an approval request, as the folder's change
 *    policy does) and describes it. The stand-in refuses any other folder or a JWT that does not
 *    verify.
 * 3. The key set then holds the one key, whose kid the login JWT names, with no private part.
 * 4. A JWT signed by another key does not verify against the set.
 *
 * Synthetic data only: the key is generated by the Worker object for the run and the secret value
 * is random; neither is printed. No identity store is needed: the Hyperdrive configs of the
 * development config point at a closed loopback port with a random password, and nothing here
 * connects to them.
 *
 *   UTS_E2E_PORT  first of the run's ports (default 9470): the mint Worker, its inspector, then the
 *                 stand-in manager at +2
 */
import { type ChildProcess, spawn } from 'node:child_process';
import { createWriteStream, mkdtempSync } from 'node:fs';
import { createServer, type IncomingMessage, type ServerResponse } from 'node:http';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { setTimeout as sleep } from 'node:timers/promises';
import { fileURLToPath } from 'node:url';
import { UTS_ENDPOINTS } from '@kilocode/uts-contracts';
import {
  createLocalJWKSet,
  createRemoteJWKSet,
  decodeProtectedHeader,
  generateKeyPair,
  jwtVerify,
  SignJWT,
} from 'jose';
import { z } from 'zod';
import { MANAGER_IDENTITIES, MANAGER_JWKS_PATH } from '../src/manager/config';

const PORT = z.coerce
  .number()
  .int()
  .positive()
  .parse(process.env.UTS_E2E_PORT ?? '9470');
const MINT = `http://127.0.0.1:${PORT}`;
const MANAGER_PORT = PORT + 2;
const ISSUER = `${UTS_ENDPOINTS.development.issuer}/manager-auth`;
const SUBJECT = 'uts:development:rotation';
const { identityId: IDENTITY_ID } = MANAGER_IDENTITIES.development;
const AUDIENCE = `https://eu.infisical.com/identities/${IDENTITY_ID}`;

const UTS_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const WORK = mkdtempSync(join(tmpdir(), 'uts-manager-auth-e2e-'));
console.log(`run directory: ${WORK}`);

let failures = 0;
function check(condition: boolean, message: string): void {
  console.log(`${condition ? 'ok  ' : 'FAIL'} ${message}`);
  if (!condition) failures += 1;
}

const JwksSchema = z.object({
  keys: z.array(z.object({ kid: z.string(), kty: z.string(), crv: z.string() }).loose()),
});
const LoginSchema = z.strictObject({ identityId: z.string(), jwt: z.string() });
const CreateSchema = z.strictObject({
  projectId: z.string(),
  environment: z.string(),
  secretPath: z.string(),
  secretValue: z.string().min(1),
  type: z.literal('shared'),
});

type Seen = {
  logins: { kid: string | undefined; iss: string; sub: string; aud: string }[];
  created: string[];
};
const seen: Seen = { logins: [], created: [] };
const remoteJwks = createRemoteJWKSet(new URL(`${MINT}${MANAGER_JWKS_PATH}`), { cacheMaxAge: 0 });

async function body(request: IncomingMessage): Promise<unknown> {
  request.setEncoding('utf8');
  let text = '';
  for await (const chunk of request) text += String(chunk);
  return JSON.parse(text || 'null');
}

function send(response: ServerResponse, status: number, payload: unknown): void {
  response.writeHead(status, { 'content-type': 'application/json' });
  response.end(JSON.stringify(payload));
}

/** The stand-in manager: JWT Auth login, then create and describe in `/admin/identity-store`. */
async function manager(request: IncomingMessage, response: ServerResponse): Promise<void> {
  const url = new URL(request.url ?? '/', `http://127.0.0.1:${MANAGER_PORT}`);
  if (request.method === 'POST' && url.pathname === '/api/v1/auth/jwt-auth/login') {
    const login = LoginSchema.safeParse(await body(request));
    if (!login.success || login.data.identityId !== IDENTITY_ID) {
      return send(response, 400, { message: 'bad login' });
    }
    try {
      const { payload } = await jwtVerify(login.data.jwt, remoteJwks, {
        algorithms: ['ES256'],
        issuer: ISSUER,
        subject: SUBJECT,
        audience: AUDIENCE,
      });
      seen.logins.push({
        kid: decodeProtectedHeader(login.data.jwt).kid,
        iss: String(payload.iss),
        sub: String(payload.sub),
        aud: String(payload.aud),
      });
    } catch (error) {
      console.log(`stand-in refused a login JWT: ${String(error)}`);
      return send(response, 401, { message: 'invalid jwt' });
    }
    return send(response, 200, {
      accessToken: 'stand-in-access',
      expiresIn: 600,
      tokenType: 'Bearer',
    });
  }
  if (request.headers.authorization !== 'Bearer stand-in-access') {
    return send(response, 401, { message: 'no token' });
  }
  const name = url.pathname.match(/^\/api\/v4\/secrets\/([A-Za-z0-9_]+)$/)?.[1];
  if (name === undefined) return send(response, 404, { message: 'no route' });
  if (request.method === 'POST') {
    const create = CreateSchema.safeParse(await body(request));
    if (!create.success || create.data.secretPath !== '/admin/identity-store') {
      return send(response, 403, { message: 'outside /admin/identity-store' });
    }
    seen.created.push(name);
    return send(response, 200, { approval: { id: 'approval-1', status: 'open' } });
  }
  if (url.searchParams.get('secretPath') !== '/admin/identity-store') {
    return send(response, 403, { message: 'outside /admin/identity-store' });
  }
  return seen.created.includes(name)
    ? send(response, 200, { secret: { id: 'secret-1', secretKey: name } })
    : send(response, 404, { message: 'Secret not found' });
}

let worker: ChildProcess | undefined;

async function waitForHttp(url: string): Promise<void> {
  for (let attempt = 0; attempt < 90; attempt += 1) {
    if (
      await fetch(url).then(
        () => true,
        () => false
      )
    )
      return;
    await sleep(1000);
  }
  throw new Error(`no answer at ${url}`);
}

async function main(): Promise<void> {
  const server = createServer((request, response) => {
    manager(request, response).catch(error => send(response, 500, { message: String(error) }));
  });
  const listening = Promise.withResolvers<void>();
  server.listen(MANAGER_PORT, '127.0.0.1', listening.resolve);
  await listening.promise;
  const log = createWriteStream(join(WORK, 'mint.log'));
  const unusedStore = `postgres://uts_app_a:${crypto.randomUUID()}@127.0.0.1:1/uts`;
  worker = spawn(
    './node_modules/.bin/wrangler',
    [
      'dev',
      '-c',
      'wrangler.dev.jsonc',
      '--ip',
      '127.0.0.1',
      '--port',
      String(PORT),
      '--inspector-port',
      String(PORT + 1),
      '--persist-to',
      join(WORK, 'state'),
      '--var',
      `MANAGER_BASE_URL:http://127.0.0.1:${MANAGER_PORT}`,
      '--var',
      `WEBAUTHN_ORIGINS:http://localhost:${PORT}`,
    ],
    {
      cwd: UTS_DIR,
      detached: true,
      stdio: ['ignore', 'pipe', 'pipe'],
      env: {
        ...process.env,
        WRANGLER_SEND_METRICS: 'false',
        XDG_CONFIG_HOME: join(WORK, 'xdg'),
        CLOUDFLARE_HYPERDRIVE_LOCAL_CONNECTION_STRING_IDENTITY_STORE: unusedStore,
        CLOUDFLARE_HYPERDRIVE_LOCAL_CONNECTION_STRING_IDENTITY_STORE_PAT: unusedStore,
        CLOUDFLARE_HYPERDRIVE_LOCAL_CONNECTION_STRING_IDENTITY_STORE_REPLICA: unusedStore,
      },
    }
  );
  worker.stdout?.pipe(log);
  worker.stderr?.pipe(log);
  try {
    await waitForHttp(`${MINT}${MANAGER_JWKS_PATH}`);

    const empty = await fetch(`${MINT}${MANAGER_JWKS_PATH}`);
    const emptySet = JwksSchema.parse(await empty.json());
    check(
      empty.status === 200 && emptySet.keys.length === 0,
      `1. key set before any login: ${empty.status} ${JSON.stringify(emptySet)}`
    );

    const write = await fetch(`${MINT}/__dev/manager/write`, { method: 'POST' });
    const written: unknown = await write.json();
    console.log(`   /__dev/manager/write: ${write.status} ${JSON.stringify(written)}`);
    check(
      z
        .object({
          created: z.object({ status: z.literal('approval_pending') }),
          described: z.object({ status: z.literal('present') }),
        })
        .safeParse(written).success,
      '2. rotation write: created as an approval request in /admin/identity-store, then described present'
    );
    const [login] = seen.logins;
    check(
      seen.logins.length === 1,
      `2. one login; stand-in verified iss=${login?.iss} sub=${login?.sub} aud=${login?.aud}`
    );
    check(
      login?.iss === ISSUER && login.sub === SUBJECT && login.aud === AUDIENCE,
      '2. claims are exact'
    );

    const full = await fetch(`${MINT}${MANAGER_JWKS_PATH}`);
    const fullSet = JwksSchema.parse(await full.json());
    console.log(
      `   key set: ${full.status} ${full.headers.get('cache-control')} ${JSON.stringify(fullSet)}`
    );
    check(
      fullSet.keys.length === 1 && fullSet.keys[0]?.kid === login?.kid,
      `3. key set holds the login key kid=${login?.kid}`
    );
    check(!JSON.stringify(fullSet).includes('"d"'), '3. no private key part');

    const other = await generateKeyPair('ES256');
    const forged = await new SignJWT({})
      .setProtectedHeader({ alg: 'ES256', kid: login?.kid })
      .setIssuer(ISSUER)
      .setSubject(SUBJECT)
      .setAudience(AUDIENCE)
      .setIssuedAt()
      .setExpirationTime('2m')
      .sign(other.privateKey);
    const local = createLocalJWKSet(fullSet);
    check(
      await jwtVerify(forged, local).then(
        () => false,
        () => true
      ),
      '4. a JWT from another key does not verify'
    );
  } finally {
    if (worker.pid !== undefined) {
      try {
        process.kill(-worker.pid, 'SIGTERM');
      } catch {
        // The Worker already exited.
      }
    }
    server.close();
  }
  console.log(
    failures === 0 ? 'PASS manager-auth-e2e' : `FAIL manager-auth-e2e: ${failures} failed`
  );
  process.exitCode = failures === 0 ? 0 : 1;
}

await main();
